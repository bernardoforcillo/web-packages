// Generates src/schema/generated/{types,vocab}.ts from the schema.org JSON-LD release.
// Usage: node scripts/generate-schema.mjs [path-to-schemaorg-current-https.jsonld]
// Without an argument the latest release is downloaded from GitHub.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const RELEASE_URL =
  "https://raw.githubusercontent.com/schemaorg/schemaorg/main/data/releases/29.2/schemaorg-current-https.jsonld";
const outDir = join(dirname(fileURLToPath(import.meta.url)), "../src/schema/generated");

const source = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(RELEASE_URL)).text();
const graph = JSON.parse(source)["@graph"];

const arr = (v) => (v === undefined ? [] : Array.isArray(v) ? v : [v]);
const local = (id) => id.replace(/^schema:/, "");
const isSchema = (id) => typeof id === "string" && id.startsWith("schema:");
const text = (v) => (typeof v === "object" && v ? v["@value"] : v) ?? "";
const idents = /^[A-Za-z_$][\w$]*$/;
// TypeScript identifiers cannot start with a digit (e.g. 3DModel).
// "3DModel" becomes "Model3D"; the literal "_3DModel" is also exported as an alias.
const T = (name) => (name.startsWith("3D") ? `${name.slice(2)}3D` : /^[0-9]/.test(name) ? `_${name}` : name);
const legacy = (name) => (T(name) !== name ? `_${name}` : null);
const key = (name) => (idents.test(name) ? name : JSON.stringify(name));

const DATA_TYPES = {
  Text: "string",
  URL: "string",
  CssSelectorType: "string",
  XPathType: "string",
  Date: "string",
  DateTime: "string",
  Time: "string",
  Number: "number | string",
  Float: "number | string",
  Integer: "number | string",
  Boolean: "boolean",
};

const classes = new Map();
const props = [];
const members = []; // enumeration members
for (const n of graph) {
  const types = arr(n["@type"]);
  if (types.includes("rdfs:Class") && !types.includes("schema:DataType")) {
    classes.set(local(n["@id"]), n);
  } else if (types.includes("rdf:Property")) {
    props.push(n);
  } else if (types.some(isSchema) && !types.includes("schema:DataType")) {
    members.push({ id: local(n["@id"]), types: types.filter(isSchema).map(local), node: n });
  }
}
for (const name of Object.keys(DATA_TYPES)) classes.delete(name);

const parents = (name) =>
  arr(classes.get(name)?.["rdfs:subClassOf"])
    .map((p) => local(p["@id"]))
    .filter((p) => classes.has(p));
const children = new Map([...classes.keys()].map((c) => [c, []]));
for (const c of classes.keys()) for (const p of parents(c)) children.get(p).push(c);
const descendants = (name, seen = new Set()) => {
  if (seen.has(name)) return seen;
  seen.add(name);
  for (const c of children.get(name) ?? []) descendants(c, seen);
  return seen;
};

// Enumerations: classes below Enumeration; their value type is the union of member IRIs.
const enumClasses = descendants("Enumeration");
const membersOf = (cls) => {
  const all = descendants(cls);
  return members.filter((m) => m.types.some((t) => all.has(t))).map((m) => m.id);
};

const comment = (n, indent) => {
  const c = String(text(n["rdfs:comment"]))
    .replace(/<[^>]+>/g, "")
    .replace(/\[\[([^\]]+)\]\]/g, "$1")
    .replace(/\s+/g, " ")
    .replace(/\*\//g, "* /")
    .trim();
  const first = (c.match(/^.*?[.!?](\s|$)/)?.[0] ?? c).trim().slice(0, 240);
  return `${indent}/** ${first}${first ? " " : ""}@see https://schema.org/${local(n["@id"])} */\n`;
};

// ---- property value types --------------------------------------------------
const propType = (p) => {
  const parts = new Set();
  let ref = false;
  for (const r of arr(p["schema:rangeIncludes"])) {
    const name = local(r["@id"]);
    if (DATA_TYPES[name]) parts.add(DATA_TYPES[name]);
    else if (classes.has(name)) {
      parts.add(T(name));
      if (!enumClasses.has(name)) ref = true;
    }
  }
  if (ref) {
    parts.add("string");
    parts.add("Ref");
  }
  if (!parts.size) parts.add("string");
  const t = [...parts].flatMap((x) => x.split(" | ")).filter((x, i, a) => a.indexOf(x) === i).join(" | ");
  return `OneOrMany<${t}>`;
};

const own = new Map([...classes.keys()].map((c) => [c, []]));
for (const p of props) {
  for (const d of arr(p["schema:domainIncludes"])) {
    const name = local(d["@id"]);
    if (own.has(name)) own.get(name).push(p);
  }
}

// URL-valued properties (range includes URL) are emitted as <link>/href in Microdata & RDFa.
const urlProps = props
  .filter((p) => {
    const r = arr(p["schema:rangeIncludes"]).map((x) => local(x["@id"]));
    return r.includes("URL");
  })
  .map((p) => local(p["@id"]))
  .sort();

// ---- emit types ---------------------------------------------------------------
let out = `// AUTO-GENERATED by scripts/generate-schema.mjs from the schema.org vocabulary. Do not edit.
/* eslint-disable */

export type OneOrMany<T> = T | readonly T[];
/** A reference to another node by its \`@id\`. */
export type Ref = { "@id": string };

`;

const names = [...classes.keys()].sort();
for (const name of names) {
  const c = classes.get(name);
  if (enumClasses.has(name)) {
    const ms = membersOf(name);
    const u = ms.length
      ? ms.flatMap((m) => [`"https://schema.org/${m}"`, `"${m}"`]).join(" | ")
      : "string";
    out += comment(c, "") + `export type ${T(name)} = ${u};\n\n`;
    continue;
  }
  const ext = parents(name).map((p) => (enumClasses.has(p) ? null : `${T(p)}Props`)).filter(Boolean);
  const base = name === "Thing" ? ' {\n  "@id"?: string;\n  "@context"?: unknown;\n' : null;
  out += comment(c, "");
  out += `export interface ${T(name)}Props${ext.length ? ` extends ${ext.join(", ")}` : ""} {${base ? base.slice(2) : "\n"}`;
  for (const p of own.get(name).sort((a, b) => (a["@id"] < b["@id"] ? -1 : 1))) {
    out += comment(p, "  ") + `  ${key(local(p["@id"]))}?: ${propType(p)};\n`;
  }
  out += "}\n";
  out += `export interface ${T(name)}Leaf extends ${T(name)}Props {\n  "@type": "${name}";\n}\n`;
  const kids = [...descendants(name)].filter((d) => !enumClasses.has(d)).sort();
  out += `export type ${T(name)} = ${kids.map((k) => `${T(k)}Leaf`).join(" | ")};\n\n`;
}

for (const name of names) {
  const alias = legacy(name);
  if (!alias) continue;
  if (enumClasses.has(name)) out += `export type ${alias} = ${T(name)};
`;
  else for (const sfx of ["", "Props", "Leaf"]) out += `export type ${alias}${sfx} = ${T(name)}${sfx};
`;
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "types.ts"), out);

writeFileSync(
  join(outDir, "vocab.ts"),
  `// AUTO-GENERATED by scripts/generate-schema.mjs. Do not edit.

/** Properties whose range includes \`URL\`; rendered as links in Microdata/RDFa. */
export const URL_PROPS: ReadonlySet<string> = new Set(${JSON.stringify(urlProps)});

/** Every schema.org type name. */
export const TYPE_NAMES: readonly string[] = ${JSON.stringify(names)};
`,
);

console.log(`${names.length} types, ${props.length} properties, ${members.length} enum members`);
